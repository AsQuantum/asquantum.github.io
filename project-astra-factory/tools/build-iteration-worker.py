# Same source and dependencies for HTTP and file://.
from pathlib import Path
import re,json,hashlib
engine=Path(__file__).resolve().parent.parent/'scripts/engine'
worker=(engine/'iteration-worker.js').read_text(encoding='utf8')
match=re.search(r"importScripts\(\.\.\.\[(.*?)\]\.map\(f=>f\+revision\)\);",worker,re.S)
assert match
deps=re.findall(r"'([^']+)'",match.group(1))
source=worker[:match.start()]+'\n'.join((engine/p).read_text(encoding='utf8') for p in deps)+worker[match.end():]
assert 'function factoryCertifiedResearchPreview(' not in source
(engine/'iteration-offline.js').write_text('// Generated by tools/build-iteration-worker.py; do not edit.\n// SHA256 '+hashlib.sha256(source.encode()).hexdigest()+'\nconst FACTORY_ITERATION_OFFLINE_SOURCE='+json.dumps(source,ensure_ascii=True)+';\n',encoding='utf8')
