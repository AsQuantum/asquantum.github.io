# Build the exact same classic worker for file:// use. No alternate math.
from pathlib import Path
import re,json,hashlib
root=Path(__file__).resolve().parent.parent
engine=root/'scripts/engine'
worker=(engine/'steady-certified-worker.js').read_text(encoding='utf8')
match=re.search(r"importScripts\(\.\.\.\[(.*?)\]\.map\(f=>f\+revision\)\);",worker,re.S)
assert match
deps=re.findall(r"'([^']+)'",match.group(1))
source=worker[:match.start()]+'\n'.join((engine/p).read_text(encoding='utf8') for p in deps)+worker[match.end():]
output='// Generated by tools/build-offline-worker.py; do not edit.\n// SHA256 '+hashlib.sha256(source.encode()).hexdigest()+'\nconst FACTORY_CERTIFIED_OFFLINE_SOURCE='+json.dumps(source,ensure_ascii=True)+';\n'
(engine/'steady-certified-offline.js').write_text(output,encoding='utf8')
