from pathlib import Path
import hashlib,json,subprocess,sys
root=Path(__file__).resolve().parent.parent
registry=json.loads((root/'docs/math-proof-registry.json').read_text(encoding='utf8'))
names=registry['activeBundleModules']
paths=registry['sourcePaths']
assert set(names)==set(paths) and len(set(names))==len(names)
parts=["'use strict';\n// Generated by tools/build-math.py from scripts/engine/math; do not edit.\n"]
for name in names:
    path=(root/paths[name]).resolve()
    assert path.is_relative_to(root/'scripts/engine/math'),path
    s=path.read_text(encoding='utf8')
    digest=hashlib.sha256(s.encode('utf8')).hexdigest()
    parts.append('// --- '+name+'.js source SHA256 '+digest+' ---\n'+s+'\n')
(root/'scripts/engine/steady-certified-proofs.js').write_text('\n'.join(parts),encoding='utf8')
subprocess.run([sys.executable,str(root/'tools/build-offline-worker.py')],check=True)
print('Built strict HTTP and offline workers from',len(names),'modules')
